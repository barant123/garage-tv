"""Regenerate the media relay's host allowlist in tools/waze-relay.js.

Collects every stream host from the iptv-org US index, sources.json and data/locals.json,
reduces them to registrable domains (example.com, or example.co.uk), and rewrites the block
between `// HOSTS:BEGIN` and `// HOSTS:END` in waze-relay.js. Hosts in EXTRA_HOSTS are kept.

    python tools/relay_hosts.py            # rewrite tools/waze-relay.js in place
    python tools/relay_hosts.py --print    # just print the list

Then paste the updated worker into the Cloudflare dashboard again.
"""
import json, os, re, sys, urllib.request
from urllib.parse import urlparse

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
US_M3U = 'https://iptv-org.github.io/iptv/countries/us.m3u'
EXTRA_HOSTS = ['test-streams.mux.dev', 'akamaized.net', 'cloudfront.net', 'amagi.tv']

def domain(h):
    if re.fullmatch(r'[\d.]+', h): return h
    p = h.split('.')
    n = 3 if len(p) >= 3 and p[-2] in ('co', 'com', 'net', 'org', 'gov') and len(p[-1]) == 2 else 2
    return '.'.join(p[-n:])

def urls_in(o):
    if isinstance(o, dict):
        for v in o.values(): yield from urls_in(v)
    elif isinstance(o, list):
        for v in o: yield from urls_in(v)
    elif isinstance(o, str) and o.startswith('http'):
        yield o

def collect():
    hosts = set(EXTRA_HOSTS)
    txt = urllib.request.urlopen(US_M3U, timeout=30).read().decode('utf-8', 'ignore')
    urls = [l.strip() for l in txt.splitlines() if l.strip().startswith('http')]
    for f in ('sources.json', 'data/locals.json'):
        try: urls += list(urls_in(json.load(open(os.path.join(ROOT, f), encoding='utf-8'))))
        except FileNotFoundError: pass
    for u in urls:
        h = urlparse(u).hostname
        if h: hosts.add(domain(h))
    return sorted(hosts)

def main():
    hosts = collect()
    block = '// HOSTS:BEGIN (generated by tools/relay_hosts.py)\nconst MEDIA_HOSTS = [\n'
    for i in range(0, len(hosts), 6):
        block += '  ' + ', '.join("'%s'" % h for h in hosts[i:i + 6]) + ',\n'
    block += '];\n// HOSTS:END'
    if '--print' in sys.argv: print(block); return
    path = os.path.join(ROOT, 'tools', 'waze-relay.js')
    src = open(path, encoding='utf-8').read()
    new = re.sub(r'// HOSTS:BEGIN.*?// HOSTS:END', lambda m: block, src, flags=re.S)
    open(path, 'w', encoding='utf-8').write(new)
    print('%d hosts written to %s' % (len(hosts), path))

if __name__ == '__main__':
    main()
